"""Headless Hex-Rays export used by `windissect decompile`.

The output is candidate pseudocode. It is never imported as verified IR.
"""

import json
import os

import ida_auto
import ida_funcs
import ida_hexrays
import ida_ida
import ida_nalt
import ida_pro
import idautils


def helper_reason(address: int) -> str | None:
    function = ida_funcs.get_func(address)
    if function is None:
        return "not an IDA function"
    name = ida_funcs.get_func_name(address)
    lowered = name.lower()
    if function.flags & ida_funcs.FUNC_LIB:
        return "IDA FLIRT/library function"
    if function.flags & ida_funcs.FUNC_THUNK:
        return "thunk"
    exact_helpers = {
        "winmaincrtstartup", "maincrtstartup", "__tmaincrtstartup", "atexit",
        "_setargv", "__main", "__do_global_ctors", "__do_global_dtors",
        "printf", "scanf", "puts", "putchar", "getchar", "malloc", "calloc",
        "realloc", "free", "memcpy", "memset", "memcmp", "strlen",
    }
    if lowered in exact_helpers:
        return "compiler startup/initialization"
    helper_fragments = (
        "mingw", "mingwthr", "libgcc", "pseudo_reloc", "tlscallback",
        "tlregdtor", "matherr", "security_cookie", "guard_", "frame_info",
        "frame_dummy", "register_frame", "deregister_frame", "crtstartup",
        "invalidparameterhandler", "mark_section_writable",
        "restore_modified_sections", "duplicate_ppstrings", "managed_app",
        "local_stdio_", "stdio_common_", "acrt_iob_func",
    )
    if any(fragment in lowered for fragment in helper_fragments):
        return "recognized compiler/runtime helper"
    return None


def direct_callees(address: int) -> set[int]:
    callees = set()
    for item in idautils.FuncItems(address):
        for target in idautils.CodeRefsFrom(item, False):
            function = ida_funcs.get_func(target)
            if function is not None:
                callees.add(function.start_ea)
    return callees


def target_functions(all_addresses: list[int]) -> tuple[list[int], list[dict]]:
    main_names = {"main", "wmain", "winmain", "wwinmain", "dllmain"}
    roots = [
        address for address in all_addresses
        if ida_funcs.get_func_name(address).lstrip("_").lower() in main_names
    ]
    if not roots:
        start = ida_ida.inf_get_start_ea()
        function = ida_funcs.get_func(start)
        if function is not None:
            roots = [function.start_ea]

    visited = set()
    root_set = set(roots)
    queue = list(roots)
    selected = []
    excluded = []
    while queue:
        address = queue.pop(0)
        if address in visited:
            continue
        visited.add(address)
        reason = helper_reason(address)
        if reason:
            excluded.append({"rva": address - ida_nalt.get_imagebase(), "name": ida_funcs.get_func_name(address), "reason": reason})
        else:
            selected.append(address)
        # Runtime/compiler boundaries stay visible as calls in the caller's C,
        # but their implementation graphs are not useful target pseudocode.
        if not reason or address in root_set:
            queue.extend(direct_callees(address) - visited)
    return sorted(selected), excluded


def main() -> None:
    output_path = os.environ.get("WINDISSECT_DECOMPILE_OUT")
    metadata_path = os.environ.get("WINDISSECT_DECOMPILE_META")
    if not output_path or not metadata_path:
        raise RuntimeError("Windissect decompiler output environment is missing")

    ida_auto.auto_wait()
    if not ida_hexrays.init_hexrays_plugin():
        raise RuntimeError("Hex-Rays decompiler is unavailable for this architecture")

    image_base = ida_nalt.get_imagebase()
    requested_rva = os.environ.get("WINDISSECT_DECOMPILE_RVA")
    scope = os.environ.get("WINDISSECT_DECOMPILE_SCOPE", "target")
    all_addresses = list(idautils.Functions())
    excluded_helpers = []
    if requested_rva:
        target = image_base + int(requested_rva, 0)
        if ida_funcs.get_func(target) is None:
            ida_funcs.add_func(target)
        addresses = [target]
        scope = "selected"
    elif scope == "target":
        addresses, excluded_helpers = target_functions(all_addresses)
    elif scope == "helpers":
        addresses = [address for address in all_addresses if helper_reason(address)]
    else:
        addresses = all_addresses
    recovered = []
    failures = []
    with open(output_path, "w", encoding="utf-8") as output:
        output.write("/*\n")
        output.write(" * WINDISSECT CANDIDATE PSEUDOCODE\n")
        output.write(" * Generated by Hex-Rays from machine code with PDB loading disabled.\n")
        output.write(" * This is reconstructed logic, not verified original source or ABI truth.\n")
        output.write(" */\n\n")
        for address in addresses:
            function = ida_funcs.get_func(address)
            if function is None:
                continue
            name = ida_funcs.get_func_name(address)
            try:
                decompiled = ida_hexrays.decompile(address)
                if decompiled is None:
                    raise RuntimeError("decompiler returned no cfunc")
                output.write(f"// RVA 0x{address - image_base:08X} | {name}\n")
                output.write(str(decompiled))
                output.write("\n\n")
                recovered.append({
                    "rva": address - image_base,
                    "name": name,
                    "size": function.end_ea - function.start_ea,
                })
            except Exception as error:
                failures.append({
                    "rva": address - image_base,
                    "name": name,
                    "error": str(error),
                })

    with open(metadata_path, "w", encoding="utf-8") as metadata:
        json.dump(
            {
                "schema": 1,
                "status": "candidate",
                "backend": "ida-hex-rays",
                "pdb_loaded": False,
                "image_base": image_base,
                "requested_rva": int(requested_rva, 0) if requested_rva else None,
                "scope": scope,
                "total_ida_functions": len(all_addresses),
                "excluded_helpers": excluded_helpers,
                "recovered": recovered,
                "failures": failures,
            },
            metadata,
            indent=2,
            sort_keys=True,
        )
        metadata.write("\n")
    print(f"decompiled {len(recovered)} functions; {len(failures)} failures")


try:
    main()
except Exception as error:
    print(f"Windissect IDA decompilation failed: {error!r}")
    ida_pro.qexit(1)
else:
    ida_pro.qexit(0)
